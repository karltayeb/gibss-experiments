#!/usr/bin/env python
"""L sensitivity: which credible sets survive a change in the number of components.

This exists because an early L=20 run produced six ahpC promoter credible sets for
isoniazid that disappear entirely at L=40 and L=60. L=20 was the wrong reading: all 20
components were active, so the cap was binding, and a saturated fit pushes components onto
whatever residual structure is left rather than reporting that it has run out of slots.
The rule this script enforces is that a reported fit must leave components unused.

Writes results/stability_L.csv and results/stability_L.md.

    uv run python scripts/05_stability.py            # every drug
    uv run python scripts/05_stability.py RIF INH
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import polars as pl
import yaml

ROOT = Path(__file__).resolve().parent.parent
PROC = ROOT / "data/processed"
RESULTS = ROOT / "results"

LADDER = [5, 10, 20, 40, 60]
MIN_LOG_BF = 2.0


def _fit_module():
    spec = importlib.util.spec_from_file_location("fit", ROOT / "scripts/03_fit.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main() -> None:
    cfg = yaml.safe_load((ROOT / "config.yaml").read_text())
    m = _fit_module()
    drugs = sys.argv[1:] or [d for d in cfg["drugs"] if (PROC / d / "X.npz").exists()]

    rows = []
    tops: dict[tuple[str, int], set[str]] = {}
    for drug in drugs:
        feat = pl.read_csv(PROC / drug / "features.csv")
        gene = dict(zip(feat["feature"].to_list(), feat["gene"].to_list()))
        for L in LADDER:
            fit = m.fit_one(drug, cfg, L=L, method=None, use_offset=True)
            table = fit["summary"].table
            strong = table.filter(pl.col("ser_log_bf") >= MIN_LOG_BF)
            top = set(strong["top"].to_list())
            tops[(drug, L)] = top
            n_active = table.filter(pl.col("active")).height
            rows.append({
                "drug": drug, "L": L, "active": n_active,
                "saturated": n_active >= L,
                "credible_sets": strong.height,
                "genes": ", ".join(
                    f"{g}:{c}" for g, c in sorted(
                        pl.Series([gene.get(t, "?") for t in strong["top"].to_list()])
                        .value_counts().iter_rows(), key=lambda kv: -kv[1])),
            })
            print(f"{drug} L={L:<3} active={n_active:<3} "
                  f"{'SATURATED' if n_active >= L else 'ok':<10} CS={strong.height}",
                  flush=True)

    frame = pl.DataFrame(rows)
    frame.write_csv(RESULTS / "stability_L.csv")

    lines = ["# L sensitivity", "",
             "Generated by `scripts/05_stability.py`.", "",
             "A fit whose active components fill every slot (`saturated`) has not been given",
             "enough components, and its extra credible sets are an artifact of the cap, not a",
             "finding. Only an unsaturated fit is reportable.", ""]
    lines.append(md := "| drug | L | active | saturated | credible sets | genes |")
    del md
    lines.append("|---|---|---|---|---|---|")
    for r in frame.iter_rows(named=True):
        lines.append(f"| {r['drug']} | {r['L']} | {r['active']} | "
                     f"{'yes' if r['saturated'] else 'no'} | {r['credible_sets']} | "
                     f"{r['genes']} |")
    lines += ["", "## Credible-set top variants by L", "",
              "`stable` lists the variants that top a credible set at every unsaturated L,",
              "which is the set worth believing. `only when saturated` lists variants that",
              "appear solely in a fit that ran out of components.", ""]
    for drug in drugs:
        unsat = [L for L in LADDER
                 if not frame.filter((pl.col("drug") == drug) & (pl.col("L") == L))["saturated"][0]]
        sat = [L for L in LADDER if L not in unsat]
        stable = set.intersection(*[tops[(drug, L)] for L in unsat]) if unsat else set()
        only_sat = (set.union(*[tops[(drug, L)] for L in sat]) - set.union(
            *[tops[(drug, L)] for L in unsat])) if sat and unsat else set()
        lines += [f"### {drug}", "",
                  f"- unsaturated L: {', '.join(map(str, unsat)) or 'none'}",
                  f"- stable across those: {', '.join(sorted(stable)) or 'none'}",
                  f"- only when saturated: {', '.join(sorted(only_sat)) or 'none'}", ""]
    (RESULTS / "stability_L.md").write_text("\n".join(lines) + "\n")
    print(f"\nwrote {RESULTS / 'stability_L.md'}")


if __name__ == "__main__":
    main()
