#!/usr/bin/env python
"""Does adjusting for covariates jointly remove the lineage-marker false positives?

Three ways of handling site, plate design and lineage, same design and L otherwise:

  none    no adjustment at all
  offset  the covariate-only fit's linear predictor, frozen (what this analysis used
          before gibss supported covariates; the coefficients never see the variants)
  joint   `fit_glm_susie(covariates=Z)`, where (b0, gamma) is one Gaussian nuisance
          factor fit alongside the effects

The measurable question is specific. Several credible sets land on common variants that
WHO grades 4 or 5, meaning it has looked and found them *not* associated with resistance:
mmpL5 Asp767Asn for clofazimine, mtrB Pro18Ser for rifampicin, aftB Asp397Gly for
ethambutol. Those are population structure, not pharmacology. If joint adjustment is doing
its job they should weaken or disappear, while the WHO group 1 and 2 calls should not.

Writes results/covariate_mode.csv and .md.

    uv run python scripts/07_covariate_mode.py            # every drug
    uv run python scripts/07_covariate_mode.py CFZ RIF
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import polars as pl
import yaml

ROOT = Path(__file__).resolve().parent.parent
PROC = ROOT / "data/processed"
RESULTS = ROOT / "results"
MODES = ("none", "offset", "joint")


def _has_design(drug: str) -> bool:
    x, f = PROC / drug / "X.npz", PROC / drug / "features.csv"
    return x.exists() and f.exists() and f.stat().st_size > 0


def _fit_module():
    spec = importlib.util.spec_from_file_location("fit", ROOT / "scripts/03_fit.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main() -> None:
    cfg = yaml.safe_load((ROOT / "config.yaml").read_text())
    m = _fit_module()
    drugs = sys.argv[1:] or [d for d in cfg["drugs"] if _has_design(d)]
    L = cfg["fit"]["L"][-1]
    min_purity = cfg["fit"]["min_purity"]

    rows, detail = [], []
    for drug in drugs:
        feat = pl.read_csv(PROC / drug / "features.csv")
        grade = dict(zip(feat["feature"].to_list(), feat["who_grade"].to_list()))
        carriers = dict(zip(feat["feature"].to_list(), feat["n_carriers"].to_list()))
        for mode in MODES:
            fit = m.fit_one(drug, cfg, L=L, method=None, covariate_mode=mode)
            table = fit["summary"].table
            strong = table.filter(pl.col("ser_log_bf") >= 2.0)
            pure = strong.filter(pl.col("purity") >= min_purity)
            tops = pure["top"].to_list()

            def count(pred):
                return sum(1 for t in tops if pred(grade.get(t)))

            # the diagnostic: a pure credible set on a COMMON variant WHO calls not
            # associated with resistance
            bad = [t for t in tops
                   if grade.get(t) is not None and grade[t] >= 4 and carriers.get(t, 0) >= 100]
            rows.append({
                "drug": drug, "mode": mode,
                "active": table.filter(pl.col("active")).height,
                "pure CS": pure.height,
                "grade 1-2": count(lambda g: g is not None and g <= 2),
                "grade 3": count(lambda g: g == 3),
                "grade 4-5 common": len(bad),
                "false positives": ", ".join(sorted(bad)),
            })
            for t in bad:
                r = pure.filter(pl.col("top") == t).row(0, named=True)
                detail.append({"drug": drug, "mode": mode, "variant": t,
                               "WHO grade": grade[t], "carriers": carriers[t],
                               "logBF": r["ser_log_bf"], "beta": r["beta"]})
            print(f"{drug} {mode:7} pure={pure.height:<3} g1-2={rows[-1]['grade 1-2']:<3} "
                  f"g4-5 common={len(bad)} {rows[-1]['false positives']}", flush=True)
            pl.DataFrame(rows).write_csv(RESULTS / "covariate_mode.csv")

    frame = pl.DataFrame(rows)
    lines = ["# Covariate handling: none vs frozen offset vs joint", "",
             "Generated by `scripts/07_covariate_mode.py`. Same design, same L="
             f"{L}, only the covariate treatment differs.", "",
             "`grade 4-5 common` counts pure credible sets whose top variant is carried by at",
             "least 100 isolates and which WHO grades 4 or 5, not associated with resistance.",
             "Those are lineage markers, so the count is a false-positive tally.", "",
             "| " + " | ".join(frame.columns) + " |",
             "|" + "|".join("---" for _ in frame.columns) + "|"]
    for r in frame.iter_rows():
        lines.append("| " + " | ".join(str(v) for v in r) + " |")
    if detail:
        d = pl.DataFrame(detail)
        lines += ["", "## The false positives, per mode", "",
                  "| " + " | ".join(d.columns) + " |",
                  "|" + "|".join("---" for _ in d.columns) + "|"]
        for r in d.iter_rows():
            lines.append("| " + " | ".join(
                f"{v:.3g}" if isinstance(v, float) else str(v) for v in r) + " |")
    (RESULTS / "covariate_mode.md").write_text("\n".join(lines) + "\n")
    print(f"\nwrote {RESULTS / 'covariate_mode.md'}")


if __name__ == "__main__":
    main()
