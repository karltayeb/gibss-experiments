#!/usr/bin/env python
"""Linear SuSiE on the 0/1 phenotype, against the logistic fit.

The question is where treating a binary outcome as Gaussian costs you. The effects here
are enormous, several variants carry an odds ratio in the hundreds, and resistance is close
to deterministic given the right mutation, which is exactly the regime where a linear model
should misbehave: a linear predictor cannot stay inside [0, 1], so it buys its fit to the
carriers by distorting everything else.

Writes results/linear_vs_logistic.csv and .md.

    uv run python scripts/06_linear_vs_logistic.py            # every drug
    uv run python scripts/06_linear_vs_logistic.py RIF INH
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import numpy as np
import polars as pl
import yaml

ROOT = Path(__file__).resolve().parent.parent
PROC = ROOT / "data/processed"
RESULTS = ROOT / "results"


def _fit_module():
    spec = importlib.util.spec_from_file_location("fit", ROOT / "scripts/03_fit.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def pips(state, p: int) -> np.ndarray:
    """Per-feature posterior inclusion probability, 1 - prod_l (1 - alpha_lj)."""
    out = np.ones(p)
    for eff in state.single_effects:
        out *= 1.0 - np.asarray(eff.alpha, dtype=float)
    return 1.0 - out


def _has_design(drug: str) -> bool:
    """A drug the pipeline skipped (no phenotype in this cohort) has no usable design.
    Checked by content, not existence: an earlier run could have left an empty table."""
    x, f = PROC / drug / "X.npz", PROC / drug / "features.csv"
    return x.exists() and f.exists() and f.stat().st_size > 0


def main() -> None:
    cfg = yaml.safe_load((ROOT / "config.yaml").read_text())
    m = _fit_module()
    drugs = sys.argv[1:] or [d for d in cfg["drugs"] if _has_design(d)]
    L = cfg["fit"]["L"][-1]
    min_purity = cfg["fit"]["min_purity"]

    rows = []
    detail = []
    for drug in drugs:
        feat = pl.read_csv(PROC / drug / "features.csv")
        names = feat["feature"].to_list()
        grade = dict(zip(names, feat["who_grade"].to_list()))
        p = len(names)

        log_fit = m.fit_one(drug, cfg, L=L, method=None, use_offset=True)
        lin_fit = m.fit_one(drug, cfg, L=L, method="linear", use_offset=True)

        def tops(fit):
            t = fit["summary"].table.filter(pl.col("ser_log_bf") >= 2.0)
            pure = t.filter(pl.col("purity") >= min_purity)
            return set(t["top"].to_list()), set(pure["top"].to_list()), t

        log_top, log_pure, log_t = tops(log_fit)
        lin_top, lin_pure, lin_t = tops(lin_fit)
        pip_log = pips(log_fit["state"], p)
        pip_lin = pips(lin_fit["state"], p)

        def g12(s):
            return sum(1 for f in s if grade.get(f) is not None and grade[f] <= 2)

        rows.append({
            "drug": drug,
            "logistic CS": log_t.height, "linear CS": lin_t.height,
            "logistic pure": len(log_pure), "linear pure": len(lin_pure),
            "logistic grade 1-2": g12(log_pure), "linear grade 1-2": g12(lin_pure),
            "shared tops": len(log_pure & lin_pure),
            "logistic only": len(log_pure - lin_pure),
            "linear only": len(lin_pure - log_pure),
            "PIP spearman": float(pl.DataFrame({"a": pip_log, "b": pip_lin})
                                  .select(pl.corr("a", "b", method="spearman")).item() or np.nan),
            "max |PIP diff|": float(np.max(np.abs(pip_log - pip_lin))),
        })
        print(f"{drug}: logistic {log_t.height} CS / linear {lin_t.height} CS, "
              f"shared pure tops {len(log_pure & lin_pure)}", flush=True)

        for f in sorted(log_pure ^ lin_pure):
            i = names.index(f)
            detail.append({
                "drug": drug, "variant": f,
                "found by": "logistic" if f in log_pure else "linear",
                "WHO grade": grade.get(f),
                "carriers": feat["n_carriers"][i],
                "pct_resistant": feat["n_carriers_resistant"][i] / feat["n_carriers"][i] * 100
                if feat["n_carriers"][i] else None,
                "PIP logistic": float(pip_log[i]), "PIP linear": float(pip_lin[i]),
            })

    frame = pl.DataFrame(rows)
    frame.write_csv(RESULTS / "linear_vs_logistic.csv")
    dframe = pl.DataFrame(detail) if detail else pl.DataFrame()

    lines = ["# Linear vs logistic SuSiE", "",
             "Generated by `scripts/06_linear_vs_logistic.py`. Both arms use the same design,",
             "the same covariate offset and the same L; only the family differs. `pure` counts",
             "credible sets reaching purity "
             f"{min_purity}, and `grade 1-2` how many of those top a WHO group 1 or 2 variant.",
             "",
             "| " + " | ".join(frame.columns) + " |",
             "|" + "|".join("---" for _ in frame.columns) + "|"]
    for r in frame.iter_rows():
        lines.append("| " + " | ".join(
            f"{v:.3g}" if isinstance(v, float) else str(v) for v in r) + " |")
    lines += ["", "## Variants found by one family only", ""]
    if dframe.height:
        lines += ["| " + " | ".join(dframe.columns) + " |",
                  "|" + "|".join("---" for _ in dframe.columns) + "|"]
        for r in dframe.iter_rows():
            lines.append("| " + " | ".join(
                "" if v is None else (f"{v:.3g}" if isinstance(v, float) else str(v))
                for v in r) + " |")
    else:
        lines.append("None: the two families selected the same pure credible-set tops.")
    lines.append("")
    (RESULTS / "linear_vs_logistic.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {RESULTS / 'linear_vs_logistic.md'}")


if __name__ == "__main__":
    main()
