#!/usr/bin/env python
"""Assemble results/summary.md from the per-drug fits.

Everything in the write-up is computed here rather than typed, so the numbers cannot
drift from the fits. Run after 03_fit.py:

    uv run python scripts/04_summarize.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import polars as pl
import yaml
from scipy import sparse

ROOT = Path(__file__).resolve().parent.parent
PROC = ROOT / "data/processed"
RESULTS = ROOT / "results"

GRADE_LABEL = {
    1: "1 assoc w R", 2: "2 assoc w R interim", 3: "3 uncertain",
    4: "4 not assoc interim", 5: "5 not assoc",
}


def load(drug: str):
    cs = RESULTS / drug / "credible_sets.csv"
    comp = RESULTS / drug / "components.csv"
    return (
        pl.read_csv(cs) if cs.exists() else None,
        pl.read_csv(comp) if comp.exists() else None,
        pl.read_csv(PROC / drug / "features.csv"),
        pl.read_csv(PROC / drug / "y.csv", schema_overrides={"mic": pl.String, "site": pl.String}),
    )


def md_table(frame: pl.DataFrame, cols: list[str], headers: list[str] | None = None) -> str:
    headers = headers or cols
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for row in frame.select(cols).iter_rows():
        cells = []
        for v in row:
            if v is None:
                cells.append("")
            elif isinstance(v, float):
                cells.append(f"{v:.3g}")
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def main() -> None:
    cfg = yaml.safe_load((ROOT / "config.yaml").read_text())
    drugs = [d for d in cfg["drugs"] if (RESULTS / d / "components.csv").exists()]
    min_purity = cfg["fit"]["min_purity"]

    lines: list[str] = []
    w = lines.append
    w("# CRyPTIC logistic SuSiE results")
    w("")
    w("Generated by `scripts/04_summarize.py`. Every number below is read from the fits in")
    w("`results/{drug}/`; none is typed by hand.")
    w("")
    w("Fit: `gibss.methods.fit_glm_susie`, logistic family, shared estimated intercept,")
    w("columns centred, prior variance estimated, sparse (BCOO) design, "
      f"L={cfg['fit']['L'][-1]}, coverage {cfg['fit']['coverage']}.")
    w("Covariates (site, plate design, Mykrobe lineage) enter as a fixed per-row offset from a")
    w("covariate-only logistic fit. Phenotype quality kept: "
      f"{', '.join(cfg['phenotype']['quality_keep'])}. Minor allele count >= "
      f"{cfg['genotype']['min_mac']}.")
    w("")

    # ---------------------------------------------------------------- overview
    w("## Per-drug overview")
    w("")
    w("Columns: `n` isolates with an R/S call of kept quality; `cases` resistant isolates;")
    w("`p` design columns (variants plus gene-level LoF burden columns); `CS` credible sets")
    w("with SER log Bayes factor >= 2; `pure CS` those also reaching purity "
      f"{min_purity}; `singleton` pure sets holding exactly one variant;")
    w("`grade 1-2 hits` pure sets whose top variant is a WHO group 1 or 2 mutation.")
    w("")
    rows = []
    for d in drugs:
        cs, comp, feat, meta = load(d)
        n_cs = n_pure = n_single = n_g12 = 0
        if cs is not None and cs.height:
            tops = (cs.sort("pip", descending=True)
                      .group_by("component", maintain_order=True).first())
            n_cs = tops.height
            pure = tops.filter(pl.col("purity") >= min_purity)
            n_pure = pure.height
            n_single = pure.filter(pl.col("cs_size") == 1).height
            n_g12 = pure.filter(pl.col("who_grade") <= 2).height
        rows.append({
            "drug": d, "n": meta.height, "cases": int(meta["y"].sum()),
            "p": feat.height, "CS": n_cs, "pure CS": n_pure,
            "singleton": n_single, "grade 1-2 hits": n_g12,
        })
    w(md_table(pl.DataFrame(rows),
               ["drug", "n", "cases", "p", "CS", "pure CS", "singleton", "grade 1-2 hits"]))
    w("")

    # ------------------------------------------------- per-drug credible sets
    w("## Credible sets by drug")
    w("")
    w("One row per credible set, showing its top variant. `logBF` is the SER log Bayes")
    w("factor for the component, `size` the number of variants in the 95% set, `purity` the")
    w("minimum absolute correlation within it. `R%` is the share of carriers that are")
    w("resistant. `LRT p` is a marginal single-variant likelihood-ratio test carrying the")
    w("same covariate offset, and `OR` with `Fisher p` the unadjusted 2x2 exact test.")
    w("")
    for d in drugs:
        cs, comp, feat, meta = load(d)
        w(f"### {d}")
        w("")
        if cs is None or not cs.height:
            w("No component reached log Bayes factor 2.")
            w("")
            continue
        tops = (cs.sort("pip", descending=True)
                  .group_by("component", maintain_order=True).first()
                  .sort("ser_log_bf", descending=True)
                  .with_columns(
                      pl.col("who_grade").replace_strict(GRADE_LABEL, default="ungraded")
                        .alias("WHO grade"),
                      pl.col("pct_resistant").alias("R%"),
                      pl.col("lrt_p").alias("LRT p"),
                      pl.col("fisher_p").alias("Fisher p"),
                      pl.col("odds_ratio").alias("OR"),
                      (pl.col("purity") >= min_purity).alias("pure"),
                  ))
        w(md_table(tops, ["component", "ser_log_bf", "cs_size", "purity", "pure", "feature",
                          "pip", "beta", "WHO grade", "who_name", "carriers", "R%",
                          "OR", "LRT p", "Fisher p"],
                   ["c", "logBF", "size", "purity", "pure", "top variant", "PIP", "beta",
                    "WHO grade", "WHO name", "carriers", "R%", "OR", "LRT p", "Fisher p"]))
        w("")

    # ------------------------------------------------------- recovery vs WHO
    w("## Recovery against the WHO catalogue")
    w("")
    w("`grade 1-2 in design` counts WHO group 1 or 2 variants that cleared the minor allele")
    w("count and so could be found at all. `in a CS` counts those that appear in some")
    w("credible set. `carrier recall` is the percentage of resistant isolates carrying at")
    w("least one variant that appears in some credible set, and")
    w("`carried by susceptible %` the same percentage among susceptible isolates, which is")
    w("the price paid for that recall.")
    w("")
    rows = []
    for d in drugs:
        cs, comp, feat, meta = load(d)
        g12 = feat.filter(pl.col("who_grade") <= 2)
        in_cs = set(cs["feature"].to_list()) if cs is not None and cs.height else set()
        # carrier recall: of the resistant isolates, how many carry at least one variant
        # that some credible set contains. This is the clinically legible number -- a
        # method can name every known mutation and still explain few actual isolates.
        X = sparse.load_npz(PROC / d / "X.npz").tocsc()
        y = meta["y"].to_numpy().astype(float)
        names = feat["feature"].to_list()
        cols = [j for j, f in enumerate(names) if f in in_cs]
        if cols:
            covered = np.asarray(X[:, cols].sum(axis=1)).ravel() > 0
            recall = float((covered & (y > 0)).sum() / max((y > 0).sum(), 1))
            fp = float((covered & (y == 0)).sum() / max((y == 0).sum(), 1))
        else:
            recall = fp = 0.0
        rows.append({
            "drug": d,
            "grade 1-2 in design": g12.height,
            "carrier recall": round(100 * recall, 1),
            "carried by susceptible %": round(100 * fp, 1),
            "in a CS": g12.filter(pl.col("feature").is_in(list(in_cs))).height
            if in_cs else 0,
            "CS variants": len(in_cs),
            "CS variants grade 1-2": feat.filter(
                pl.col("feature").is_in(list(in_cs)) & (pl.col("who_grade") <= 2)).height
            if in_cs else 0,
            "CS variants grade 3": feat.filter(
                pl.col("feature").is_in(list(in_cs)) & (pl.col("who_grade") == 3)).height
            if in_cs else 0,
            "CS variants grade 4-5": feat.filter(
                pl.col("feature").is_in(list(in_cs)) & (pl.col("who_grade") >= 4)).height
            if in_cs else 0,
        })
    w(md_table(pl.DataFrame(rows), list(rows[0])))
    w("")

    # ------------------------------- uncertain-significance variants promoted
    w("## WHO group 3 variants in pure credible sets")
    w("")
    w("These are the catalogue's \"uncertain significance\" calls that this fit places in a")
    w("pure credible set. They are the discovery claim worth checking: the model says the")
    w("evidence points at them specifically, having had the chance to point at a")
    w("co-occurring variant instead.")
    w("")
    promoted = []
    for d in drugs:
        cs, comp, feat, meta = load(d)
        if cs is None or not cs.height:
            continue
        tops = (cs.sort("pip", descending=True)
                  .group_by("component", maintain_order=True).first())
        sel = tops.filter((pl.col("who_grade") == 3) & (pl.col("purity") >= min_purity)
                          & (pl.col("pip") >= 0.5))
        for r in sel.iter_rows(named=True):
            promoted.append({
                "drug": d, "variant": r["feature"], "WHO name": r["who_name"],
                "logBF": r["ser_log_bf"], "PIP": r["pip"], "beta": r["beta"],
                "carriers": r["carriers"], "resistant": r["carriers_resistant"],
                "R%": r["pct_resistant"], "OR": r["odds_ratio"],
                "LRT p": r["lrt_p"], "Fisher p": r["fisher_p"],
            })
    if promoted:
        w(md_table(pl.DataFrame(promoted).sort("logBF", descending=True), list(promoted[0])))
    else:
        w("None.")
    w("")

    # --------------------------------------------------- diagnostics / caveats
    w("## Diagnostics")
    w("")
    w("### Effect splitting: one variant topping two components")
    w("")
    w("A very large effect can be shared between two components, which inflates the count")
    w("of credible sets. Each row is a variant that tops more than one set in the same fit.")
    w("")
    split = []
    for d in drugs:
        cs, comp, feat, meta = load(d)
        if cs is None or not cs.height:
            continue
        tops = (cs.sort("pip", descending=True)
                  .group_by("component", maintain_order=True).first())
        dup = (tops.group_by("feature").agg(
                   pl.len().alias("components"),
                   pl.col("beta").sort(descending=True).alias("betas"))
                 .filter(pl.col("components") > 1))
        for r in dup.iter_rows(named=True):
            split.append({"drug": d, "variant": r["feature"],
                          "components": r["components"],
                          "betas": ", ".join(f"{b:.2f}" for b in r["betas"])})
    w(md_table(pl.DataFrame(split), list(split[0])) if split else "None.")
    w("")

    w("### Near separation")
    w("")
    w("Variants whose carriers are all resistant have an infinite maximum-likelihood odds")
    w("ratio. The prior keeps the posterior finite, but the effect size is then set by the")
    w("prior rather than the data, which is why these betas are an order of magnitude above")
    w("the rest. Listed are credible-set top variants with every carrier resistant.")
    w("")
    sep = []
    for d in drugs:
        cs, comp, feat, meta = load(d)
        if cs is None or not cs.height:
            continue
        tops = (cs.sort("pip", descending=True)
                  .group_by("component", maintain_order=True).first())
        for r in tops.filter(pl.col("pct_resistant") >= 100.0).iter_rows(named=True):
            sep.append({"drug": d, "variant": r["feature"], "WHO name": r["who_name"],
                        "carriers": r["carriers"], "beta": r["beta"],
                        "logBF": r["ser_log_bf"]})
    w(md_table(pl.DataFrame(sep).sort("beta", descending=True), list(sep[0]))
      if sep else "None.")
    w("")

    w("### High-frequency variants graded \"not associated with resistance\"")
    w("")
    w("A credible set on a common variant that WHO grades 4 or 5, usually with a negative")
    w("effect, is the signature of population structure the covariate offset did not")
    w("absorb. These are lineage markers, not resistance mechanisms, and they are the")
    w("clearest evidence that the lineage-indicator offset is too coarse and genome-wide")
    w("principal components are needed.")
    w("")
    lin = []
    for d in drugs:
        cs, comp, feat, meta = load(d)
        if cs is None or not cs.height:
            continue
        tops = (cs.sort("pip", descending=True)
                  .group_by("component", maintain_order=True).first())
        for r in tops.filter((pl.col("who_grade") >= 4) & (pl.col("carriers") >= 100)).iter_rows(named=True):
            lin.append({"drug": d, "variant": r["feature"], "WHO name": r["who_name"],
                        "WHO grade": r["who_grade"], "carriers": r["carriers"],
                        "R%": r["pct_resistant"], "beta": r["beta"],
                        "logBF": r["ser_log_bf"]})
    w(md_table(pl.DataFrame(lin).sort("logBF", descending=True), list(lin[0]))
      if lin else "None.")
    w("")

    w("### Gene-level LoF burden columns in credible sets")
    w("")
    w("A burden column is 1 when the isolate carries any frameshift, premature stop or lost")
    w("start in that gene. It is the test of whether allelic heterogeneity defeats a")
    w("per-variant model: if the burden column is in a credible set and none of its")
    w("constituent variants is, the signal exists only once the variants are pooled.")
    w("")
    bur = []
    for d in drugs:
        cs, comp, feat, meta = load(d)
        if cs is None or not cs.height:
            continue
        for r in cs.filter(pl.col("mutation") == "LoF_burden").iter_rows(named=True):
            bur.append({"drug": d, "column": r["feature"], "component": r["component"],
                        "logBF": r["ser_log_bf"], "PIP": r["pip"], "cs_size": r["cs_size"],
                        "WHO grade": r["who_grade"], "carriers": r["carriers"],
                        "R%": r["pct_resistant"]})
    w(md_table(pl.DataFrame(bur).sort("logBF", descending=True), list(bur[0]))
      if bur else "None.")
    w("")

    w("### Perfectly confounded variants collapsed before fitting")
    w("")
    w("Variants with an identical carrier set cannot be told apart by any method, so they")
    w("enter as one column. The count below is how many were folded away per drug.")
    w("")
    rows = []
    for d in drugs:
        c = PROC / d / "collapsed.csv"
        f = pl.read_csv(c) if c.exists() else None
        rows.append({"drug": d, "columns with a twin": 0 if f is None else f.height})
    w(md_table(pl.DataFrame(rows), ["drug", "columns with a twin"]))
    w("")

    # L sensitivity, if scripts/05_stability.py has been run. Reported here because the
    # number of credible sets is not a property of the data alone: a fit that uses every
    # component it was given has run out, and its extra sets are an artifact of the cap.
    stab = RESULTS / "stability_L.csv"
    w("## L sensitivity")
    w("")
    if stab.exists():
        sf = pl.read_csv(stab)
        w("From `scripts/05_stability.py`. A fit marked `saturated` filled every component")
        w("slot and is not reportable; the reported fits below use "
          f"L={cfg['fit']['L'][-1]}.")
        w("")
        w(md_table(sf.with_columns(
            pl.when(pl.col("saturated")).then(pl.lit("yes")).otherwise(pl.lit("no"))
            .alias("saturated")),
            ["drug", "L", "active", "saturated", "credible_sets"],
            ["drug", "L", "active", "saturated", "credible sets"]))
        w("")
        bad = sf.filter(pl.col("saturated"))
        if bad.height:
            w("Saturated, therefore excluded: "
              + ", ".join(f"{r['drug']} at L={r['L']}" for r in bad.iter_rows(named=True))
              + ". See `stability_L.md` for which variants appear only in those fits.")
            w("")
    else:
        w("Not yet run; see `scripts/05_stability.py`.")
        w("")

    out = RESULTS / "summary.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
