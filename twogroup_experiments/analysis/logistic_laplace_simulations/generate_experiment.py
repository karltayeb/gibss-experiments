"""Generate experiments/022_logistic_laplace.yaml from betas.json.

022 asks when gIBSS-Laplace (the simplest logistic SuSiE: Laplace SER + plug-in offset) is
good enough. Four Q2 arms, each at L=1 and L=10, all scored on the same exact Q2 ELBO:

  gIBSS-Laplace  order-1 quad SER (Laplace evidence), plug-in mean offset, reduced to Q2
  gIBSS-Q2       Gaussian-VI SER (GH over b), plug-in mean offset
  global-JJ      Jaakkola-Jordan quadratic bound, one shared tilt (jj_fixed)
  CAVI-Q2        Gaussian-VI SER, exact offset fold (cf)

Axis: expected set size m in {5, 10, 30, 100} of a sparse 0/1 design (n=10000, p=256,
corr=0.8, b0=-2), with beta calibrated per m to E[LRT] = T (calibrate.py -> betas.json).
Detectability is matched along the axis; small m forces large beta and a skewed per-feature
likelihood, where Laplace should visibly miss. Large m is the Bernstein-von Mises end.

Two supercollections over shared content-addressed cells (labels are display-only):
  * 022-laplace        full grid, 50 reps (rpb=10 x n_batches=5)
  * 022-laplace-pilot  subset (T in {8,16} + nulls + one multi cell per m), 10 reps

Cells per m: 3 T single-effect + 1 null + 2 L* x 2 gap multi (T=8) = 8; x4 m = 32 cells.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "experiments" / "022_logistic_laplace.yaml"

N_BATCHES = 5
N, P, CORR, B0 = 10000, 256, 0.8, -2.0
SET_SIZES = [5, 10, 30, 100]
TARGETS = [4, 8, 16]
LSTARS = [2, 3]
GAPS = [2, 10]
MULTI_T = 8

PILOT_TARGETS = [8, 16]
PILOT_MULTI = (3, 10)             # (L*, gap) at T=MULTI_T

METHODS = [
    "logistic_q2_ser_gibss_laplace", "logistic_q2_ser_gibss", "logistic_q2_ser_globaljj",
    "logistic_q2_ser_cavi",
    "logistic_q2_L10_gibss_laplace", "logistic_q2_L10_gibss", "logistic_q2_L10_globaljj",
    "logistic_q2_L10_cavi",
]


def _design(m: int) -> str:
    return (f"{{function: binary_markov_X, arguments: "
            f"{{n: {N}, p: {P}, corr: {CORR}, density: {m / N:g}}}}}")


def _single(m: int, t: int, beta: float) -> str:
    return (f"- {{label: ser_m{m}_T{t}, function: uniform_single_effect, "
            f"arguments: {{causal_effect: {beta:.4f}}}, intercept: {B0:.1f}}}")


def _null(m: int) -> str:
    return (f"- {{label: null_m{m}, function: uniform_single_effect, "
            f"arguments: {{causal_effect: 0.0}}, intercept: {B0:.1f}}}")


def _multi(m: int, lstar: int, gap: int, beta: float) -> str:
    effects = ", ".join(f"{beta:.4f}" for _ in range(lstar))
    return (f"- {{label: mc{lstar}_m{m}_T{MULTI_T}_g{gap}, function: spaced_index_effect, "
            f"arguments: {{causal_effects: [{effects}], gap: {gap}}}, intercept: {B0:.1f}}}")


def entries(m: int, betas: dict, *, pilot: bool) -> list[str]:
    tbl = betas[str(m)]
    rows = [_single(m, t, tbl[str(t)]) for t in (PILOT_TARGETS if pilot else TARGETS)]
    rows.append(_null(m))
    multi = [PILOT_MULTI] if pilot else [(ls, g) for ls in LSTARS for g in GAPS]
    rows += [_multi(m, ls, g, tbl[str(MULTI_T)]) for ls, g in multi]
    return rows


def collections_block(betas: dict, indent: str, *, pilot: bool) -> str:
    """One collection per set size (the design density differs per m)."""
    blocks = []
    for m in SET_SIZES:
        lines = "\n".join(f"{indent}        {e}" for e in entries(m, betas, pilot=pilot))
        blocks.append(
            f"{indent}- template: {{design: {_design(m)}, signal: binary, error: noiseless}}\n"
            f"{indent}  over:\n"
            f"{indent}    enrichment:\n{lines}"
        )
    return "\n".join(blocks)


def main() -> None:
    betas = json.loads((HERE / "betas.json").read_text())["betas"]
    n_cells = len(SET_SIZES) * (len(TARGETS) + 1 + len(LSTARS) * len(GAPS))
    n_pilot = len(SET_SIZES) * (len(PILOT_TARGETS) + 1 + 1)
    methods_yaml = "[" + ", ".join(METHODS) + "]"
    text = f"""\
# 022_logistic_laplace: when is gIBSS-Laplace good enough? Four Q2 logistic-SuSiE arms at
# L=1 and L=10 -- gIBSS-Laplace (order-1 SER, plug-in offset, reduced to Q2), gIBSS-Q2
# (Gaussian-VI SER, plug-in offset), global-JJ (jj_fixed bound), CAVI-Q2 (Gaussian-VI SER,
# exact cf offset fold) -- all scored on the exact Q2 ELBO. Centered, shared Gaussian intercept, EB prior variance (cap 100).
#
# Axis: expected set size m in {{{", ".join(map(str, SET_SIZES))}}} of a sparse 0/1 design (n={N}, p={P},
# corr={CORR}, b0={B0:g}); beta calibrated per m to E[LRT] = T in {{{", ".join(map(str, TARGETS))}}}
# (analysis/logistic_laplace_simulations/calibrate.py -> betas.json). Small m = skewed per-feature
# likelihood (Laplace misses); large m = Bernstein-von Mises (Laplace exact). This file is
# GENERATED by generate_experiment.py -- edit that, not this.
_anchors:
  methods: &methods {methods_yaml}
  default_args: &default_args {{min_log_bf: 2.0, max_cs_size: 10000, max_fdp: 0.5}}

supercollections:
  # full grid: {n_cells} cells, {N_BATCHES * 10} reps
  022-laplace:
    replicates_per_batch: 10
    n_batches: {N_BATCHES}
    collections:
{collections_block(betas, "      ", pilot=False)}
    methods: *methods
    default_args: *default_args
    outputs:
      - {{name: laplace, method_filter: *methods, analyses: [pip, cs]}}

  # pilot: {n_pilot}-cell content subset of 022-laplace (T in {{{", ".join(map(str, PILOT_TARGETS))}}}, nulls, mc{PILOT_MULTI[0]} gap {PILOT_MULTI[1]}),
  # 10 reps. Cells and batch 0 are content-identical to the full run, so they are reused.
  022-laplace-pilot:
    replicates_per_batch: 10
    n_batches: 1
    collections:
{collections_block(betas, "      ", pilot=True)}
    methods: *methods
    default_args: *default_args
    outputs:
      - {{name: pilot, method_filter: *methods, analyses: [pip, cs]}}
"""
    OUT.write_text(text)
    print(f"wrote {OUT} ({n_cells} cells full, {n_pilot} pilot, {len(METHODS)} methods)")


if __name__ == "__main__":
    main()
