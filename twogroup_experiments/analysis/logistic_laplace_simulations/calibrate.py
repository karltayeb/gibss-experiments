"""Calibrate the 022 Laplace-axis betas: E[LRT] = T at each expected set size m.

The axis is the expected set size m = n * density of a sparse 0/1 design column (n rows,
b0 = -2). At fixed detectability T, a small set forces a large beta, so each feature's
in-set likelihood is skewed (few informative rows, near quasi-separation) and the Laplace
approximation N(mode, 1/H) misses the exact posterior. At large m the likelihood is near
Gaussian and Laplace is exact. Calibrating beta to E[LRT] = T holds detectability fixed, so
the only thing that varies along the axis is how Gaussian each feature's likelihood is.

Uses the exact 2x2 G-test expectation from 019's calibration.py (profiled intercept, set size
averaged over m ~ Binomial(n, density)). Writes one table per design, keyed betas[m][T]:
betas.json (n=10000, the pilot) and betas_n1000.json (n=1000, the full 022 grid).

Run: uv run python analysis/logistic_laplace_simulations/calibrate.py [betas_n1000.json ...]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from scipy.optimize import brentq

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "logistic_susie_simulations"))
from calibration import e_lrt_binary  # noqa: E402

B0 = -2.0
# output file -> (n rows, expected set sizes m = n * density, E[LRT] targets)
TABLES = {
    "betas.json": (10000, [5, 10, 30, 100], [4, 8, 16]),       # pilot (T=32 unreachable at m=5)
    "betas_n1000.json": (1000, [5, 10, 50, 100, 200, 400], [16]),   # full 022 grid
}


def invert(n: int, m: int, target: float) -> float:
    return brentq(lambda b: e_lrt_binary(n, m / n, B0, b) - target, 1e-3, 8.0, xtol=1e-5)


def write_table(name: str) -> None:
    n, set_sizes, targets = TABLES[name]
    betas = {str(m): {str(t): round(invert(n, m, t), 4) for t in targets} for m in set_sizes}
    out = {
        "_meta": {
            "quantity": "beta that hits target E[LRT] (intercept PROFILED), binary column",
            "n": n, "b0": B0, "set_sizes": set_sizes, "targets_lrt": targets,
            "note": "exact 2x2 G-test expectation, set size ~ Binomial(n, m/n). "
                    "Generated by calibrate.py.",
        },
        "betas": betas,
    }
    (HERE / name).write_text(json.dumps(out, indent=2) + "\n")
    print(name)
    for m in set_sizes:
        print(f"  m={m:>3d}  " + "  ".join(f"T={t:<2d}->{betas[str(m)][str(t)]:.4f}" for t in targets))


def main() -> None:
    for name in (sys.argv[1:] or list(TABLES)):
        write_table(name)


if __name__ == "__main__":
    main()
