"""Calibrate betas for the two 022 analogs (023 Gaussian n=500, 024 nested n=1000), E[LRT] = T, b0=-2.

* betas_gaussian_n500.json: one beta per T in {4,8,12,16,20,24} for a standard-normal column (n=500) (the AR1 Gaussian
  design's marginal is N(0,1) whatever rho, so the table has no rho axis). Monte Carlo
  inversion via 019's ``e_lrt_gaussian_mc`` (profiled intercept), bisection to 1e-3.
* betas_nested_n1000.json: one beta per (depth, T) for a binary column of the attrition design
  (density 0.5, drop 0.45): a column at depth d has expected size n * 0.5 * 0.55**d, and the
  exact 2x2 G-test expectation of 019 (set size ~ Binomial(n, density_d)) is inverted as in
  022's calibrate.py. Keyed betas[depth][T].

Run: uv run python analysis/logistic_laplace_simulations/calibrate_analogs.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from scipy.optimize import brentq

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "logistic_susie_simulations"))
from calibration import e_lrt_binary, e_lrt_gaussian_mc  # noqa: E402

N, B0, TARGETS = 1000, -2.0, [8, 16]
GAUSS_TARGETS = [4, 8, 12, 16, 20, 24]          # 023 sweeps T at fixed rho
GAUSS_N = 500                                   # 023 = 019's Gaussian design size
ROOT_DENSITY, DROP, DEPTHS = 0.5, 0.45, list(range(8))


def gaussian_table() -> dict:
    def invert(t):
        lo, hi = 0.0, 4.0
        for _ in range(40):
            mid = 0.5 * (lo + hi)
            if e_lrt_gaussian_mc(GAUSS_N, B0, mid, n_rep=4000)["lrt"] < t:
                lo = mid
            else:
                hi = mid
            if hi - lo < 1e-3:
                break
        return round(0.5 * (lo + hi), 4)
    betas = {str(t): invert(t) for t in GAUSS_TARGETS}
    return {"_meta": {"quantity": "beta hitting target E[LRT] (intercept PROFILED), N(0,1) column",
                      "n": GAUSS_N, "b0": B0, "targets_lrt": GAUSS_TARGETS,
                      "note": "MC (4000 reps) over x~N(0,1), bisection; rho-free. Generated by calibrate_analogs.py."},
            "betas": betas}


def nested_table() -> dict:
    betas = {}
    for d in DEPTHS:
        dens = ROOT_DENSITY * (1.0 - DROP) ** d
        betas[str(d)] = {str(t): round(brentq(lambda b: e_lrt_binary(N, dens, B0, b) - t, 1e-3, 8.0, xtol=1e-5), 4)
                         for t in TARGETS}
    return {"_meta": {"quantity": "beta hitting target E[LRT] (intercept PROFILED), binary column at attrition depth d",
                      "n": N, "b0": B0, "root_density": ROOT_DENSITY, "drop": DROP, "depths": DEPTHS,
                      "expected_sizes": {str(d): round(N * ROOT_DENSITY * (1 - DROP) ** d, 1) for d in DEPTHS},
                      "targets_lrt": TARGETS,
                      "note": "exact 2x2 G-test expectation, set size ~ Binomial(n, 0.5*0.55^d). Generated by calibrate_analogs.py."},
            "betas": betas}


def main() -> None:
    g = gaussian_table(); (HERE / "betas_gaussian_n500.json").write_text(json.dumps(g, indent=2) + "\n")
    print("gaussian:", g["betas"])
    nt = nested_table(); (HERE / "betas_nested_n1000.json").write_text(json.dumps(nt, indent=2) + "\n")
    for d in DEPTHS:
        print(f"nested depth {d} (m~{nt['_meta']['expected_sizes'][str(d)]}): {nt['betas'][str(d)]}")


if __name__ == "__main__":
    main()
